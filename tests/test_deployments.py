def test_the_unnamed_deployment_keeps_every_name_it_had():
    names = deployment.names_for("")
    assert (names.deploy_workflow, names.release_workflow) == ("deploy.yml", "release.yml")
    assert (names.config_secret, names.config_digest) == ("DEPLOYCTL_CONFIG", "DEPLOYCTL_CONFIG_DIGEST")
    assert (names.ssh_key_secret, names.known_hosts) == ("DEPLOY_SSH_KEY", "DEPLOY_KNOWN_HOSTS")
    assert (names.auto_deploy, names.app_url) == ("AUTO_DEPLOY", "APP_URL")
    assert names.github_environment("production") == "production"


def test_a_named_deployment_has_its_own():
    names = deployment.names_for("eu-west")
    assert names.deploy_workflow == "deploy-eu-west.yml"
    assert names.config_secret == "DEPLOYCTL_CONFIG_EU_WEST"
    assert names.ssh_key_secret == "DEPLOY_SSH_KEY_EU_WEST"
    assert names.auto_deploy == "AUTO_DEPLOY_EU_WEST"
    assert names.github_environment("production") == "eu-west"
    assert names.github_environment("staging") == "eu-west-staging"


# ---- the bundle -----------------------------------------------------------------------------


FILES = {"production.env": "MODE=single\n", "secrets.production.env": "SECRET_KEY=a\n"}


def test_an_unnamed_bundle_is_byte_for_byte_what_it_was():
    """deploy/'s digest in GitHub stays valid, and an older deployctl in CI decodes it."""
    assert bundle.digest(FILES) == bundle.digest(FILES, "")
    assert b'"deployment"' not in bundle._canonical(FILES)


def test_a_bundle_made_for_another_deployment_is_refused():
    named = bundle.encode(FILES, "sentinel")
    assert bundle.decode(named, "production", "sentinel") == FILES
    with pytest.raises(bundle.BundleError, match="made for deployment 'sentinel'"):
        bundle.decode(named, "production")
    with pytest.raises(bundle.BundleError, match="made for the unnamed deployment"):
        bundle.decode(bundle.encode(FILES), "production", "sentinel")
    assert bundle.digest(FILES, "sentinel") != bundle.digest(FILES)


