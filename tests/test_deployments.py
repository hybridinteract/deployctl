def test_ci_deploy_runs_the_deployments_own_workflow(repo, monkeypatch):
    dispatched = []
    monkeypatch.setattr(github, "dispatch", lambda workflow, ref, fields: dispatched.append((workflow, ref, fields)))
    result = _cli(repo / "deploy-sentinel", "ci", "deploy", "--env", "production", "--tag", "abc1234", "--no-watch")
    assert result.exit_code == 0, result.output
    assert dispatched == [("deploy-sentinel.yml", "prod-sentinel", {
        "environment": "production", "tag": "abc1234", "action": "update", "allow_config_change": "false"})]


def test_unpack_takes_the_bundle_its_workflow_names(repo, monkeypatch, tmp_path):
    """In CI: the named workflow maps DEPLOYCTL_CONFIG_SENTINEL onto DEPLOYCTL_CONFIG."""
    files = {name: (repo / "deploy-sentinel" / "config" / name).read_text()
             for name in ("common.env", "production.env", "secrets.production.env")}
    ci_checkout = _folder(tmp_path / "checkout" / "deploy-sentinel", "")
    for name in files:
        (ci_checkout / "config" / name).unlink(missing_ok=True)
    monkeypatch.setenv("DEPLOYCTL_CONFIG", bundle.encode(files, "sentinel"))
    monkeypatch.setenv("DEPLOYCTL_CONFIG_DIGEST", bundle.digest(files, "sentinel"))

    refused = _cli(ci_checkout, "ci", "unpack", "--env", "production")
    assert refused.exit_code == 1 and "made for deployment 'sentinel'" in refused.output

    result = _cli(ci_checkout, "ci", "unpack", "--env", "production", "--deployment", "sentinel")
    assert result.exit_code == 0, result.output
    assert (ci_checkout / "config" / "common.env").read_text() == files["common.env"]


def test_doctor_checks_the_deployments_own_secrets(repo, monkeypatch):
    import subprocess

    monkeypatch.setattr(github, "secret_names", lambda scope: {"DEPLOY_SSH_KEY", "DEPLOYCTL_CONFIG"})
    monkeypatch.setattr(github, "variables", lambda scope: {"DEPLOYCTL_CONFIG_DIGEST": "sha256:x"})
    monkeypatch.setattr(github, "gh", lambda args, stdin=None: subprocess.CompletedProcess(args, 0, "PUBLIC\n", ""))
    items = {item["id"]: item for item in ci.doctor_items(_use(repo / "deploy-sentinel"))}
    # deploy/'s secrets are set; this deployment's are not, and must not count.
    assert items["ssh-key"]["status"] == "todo" and "DEPLOY_SSH_KEY_SENTINEL" in items["ssh-key"]["title"]
    assert items["config"]["status"] == "todo"
    assert items["deployment"]["status"] == "ok"
    assert {"workflow:deploy-sentinel.yml", "workflow:release-sentinel.yml"} <= set(items)
    assert "workflow:build-image.yml" not in items


