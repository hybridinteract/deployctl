def test_each_folder_is_its_own_project_with_its_own_port(repo, tmp_path, monkeypatch):
    monkeypatch.setenv("DEPLOYCTL_HOME", str(tmp_path / "home"))
    main, added = projects.add(repo)
    assert added and main.deploy == "deploy"
    sentinel, added = projects.add(repo / "deploy-sentinel")
    assert added and sentinel.deploy == "deploy-sentinel"
    assert sentinel.port != main.port and sentinel.name == "acme-sentinel"

    again, added = projects.add(repo / "deploy")
    assert not added and again == main  # same name, same port: bookmarks keep working
    assert {p.name for p in projects.load()} == {"acme", "acme-sentinel"}
    assert projects.for_deploy_dir(repo / "deploy-sentinel") == sentinel
    assert projects.for_repo(repo) == main


def test_a_registry_from_before_keeps_its_entry(repo, tmp_path, monkeypatch):
    """A version-1 file written by 0.15: one entry, deploy="deploy". Adding the repository
    again matches it, and the new folder is added beside it."""
    monkeypatch.setenv("DEPLOYCTL_HOME", str(tmp_path / "home"))
    projects.registry_file().parent.mkdir(parents=True, exist_ok=True)
    projects.registry_file().write_text(json.dumps({"version": 1, "projects": [
        {"name": "herbally-backend", "root": str(repo.resolve()), "port": 8767, "deploy": "deploy"}]}))
    project, added = projects.add(repo)
    assert not added and (project.name, project.port) == ("herbally-backend", 8767)
    projects.add(repo / "deploy-sentinel")
    assert next(p for p in projects.load() if p.name == "herbally-backend").port == 8767


def test_a_named_folder_that_is_gone_is_not_mistaken_for_deploy(repo):
    gone = projects.Project("old", str(repo), 8799, "deploy-gone")
    assert gone.deploy_dir is None
    assert projects.Project("main", str(repo), 8767, "deploy").deploy_dir == repo / "deploy"


