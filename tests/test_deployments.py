def test_init_again_for_an_existing_deployment_changes_nothing(repo, tmp_path, monkeypatch):
    """As init always is: the folder is found again, and no file someone filled in is touched."""
    monkeypatch.setenv("DEPLOYCTL_HOME", str(tmp_path / "home"))
    before = {p: p.read_bytes() for p in (repo / "deploy-sentinel").rglob("*") if p.is_file()}
