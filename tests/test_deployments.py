"""Several deployments of one repository: deploy/ as it always was, and deploy-<name>/ beside it.

The repository's deploy/ needs no name and keeps every name it had. A further folder
sets DEPLOYMENT and gets its own workflows, GitHub secrets and variables, deploy lock,
config bundle and control panel — so nothing it does reaches deploy/'s. GitHub is
stood in for, as in test_ci_commands.
"""

from __future__ import annotations

import json
import pathlib

import pytest
from typer.testing import CliRunner

from deployctl.cli import bundle, config, deployment, github, paths, projects
from deployctl.cli.commands import ci
from deployctl.cli.main import app

PROJECT_ENV = "APP_MODULE=app.main:app\nCELERY_APP=app.worker\nCELERY_QUEUES=default\nMIGRATE_CMD=alembic upgrade head\n"
ENV = """\
MODE=single
HOSTS=203.0.113.10
ACME_EMAIL=ops@acme.test
POSTGRES_DB=app
POSTGRES_USER=app
"""
SECRETS = "SECRET_KEY=a\nJWT_SECRET_KEY=b\nREDIS_PASSWORD=c\nPOSTGRES_PASSWORD=d\n"
COMMON = "PROJECT_NAME={name}\nBASE_DOMAIN=acme.test\nIMAGE_REPO=ghcr.io/acme/backend\nCI_SCOPE=repository\n"

#: What a production repository already has, in the shapes herbally's are: a
#: 0.14-managed deploy.yml with a local edit, and a hand-written release.yml.
EXISTING = {
    "build-image.yml": "# Managed by deployctl 0.14.0 — regenerate with: deployctl ci init --force\nname: build-image\n",
    "ci.yml": "# Written once by deployctl 0.14.0\nname: CI\njobs:\n  publish:\n    uses: ./.github/workflows/build-image.yml\n",
    "deploy.yml": "# Managed by deployctl 0.14.0 — regenerate with: deployctl ci init --force\n# LOCAL EDIT\nname: deploy\n",
    "release.yml": "# Not generated by deployctl — this file is ours\nname: release\njobs:\n  deploy:\n"
                   "    uses: ./.github/workflows/deploy.yml\n",
}


def _folder(root: pathlib.Path, common: str) -> pathlib.Path:
    for name in ("config", "project", "generated"):
        (root / name).mkdir(parents=True, exist_ok=True)
    (root / "project" / "project.env").write_text(PROJECT_ENV)
    (root / "config" / "common.env").write_text(common)
    (root / "config" / "production.env").write_text(ENV)
    (root / "config" / "secrets.production.env").write_text(SECRETS)
    return root


@pytest.fixture
def repo(tmp_path, monkeypatch):
    """A repository with deploy/ (unnamed, released from prod) and deploy-sentinel/
    (DEPLOYMENT=sentinel, released from prod-sentinel), both built on main."""
    # Every global set_project_root changes, restored after the test.
    for name in ("ROOT", "CONFIG_DIR", "PROJECT_DIR", "GENERATED_DIR", "REPO_ROOT", "CI_WORKFLOW", "COMMON_CONFIG",
                 "PROJECT_CONFIG", "PROJECT_APP_ENV_TEMPLATE", "PROJECT_FIELDS", "PROJECT_COMPOSE_EXTRA",
                 "PROJECT_NGINX_EXTRA"):
        monkeypatch.setattr(paths, name, getattr(paths, name))
    monkeypatch.setenv("DEPLOYCTL_PROJECT", "unset-by-the-test")
    monkeypatch.delenv("DEPLOYCTL_PROJECT")

    top = tmp_path / "repo"
    (top / ".git").mkdir(parents=True)
    _folder(top / "deploy", COMMON.format(name="acme") + "DEPLOY_BRANCH=prod\nBUILD_BRANCH=main\n")
    _folder(top / "deploy-sentinel", COMMON.format(name="acme-sentinel")
            + "DEPLOYMENT=sentinel\nDEPLOY_BRANCH=prod-sentinel\nBUILD_BRANCH=main\n")
    workflows = top / ".github" / "workflows"
    workflows.mkdir(parents=True)
    for name, text in EXISTING.items():
        (workflows / name).write_text(text)

    monkeypatch.setattr(github, "require", lambda: None)
    monkeypatch.setattr(github, "repo", lambda: {"name": "acme/backend", "owner": "acme", "private": True,
                                                 "default_branch": "main", "permission": "ADMIN"})
    return top


def _cli(folder: pathlib.Path, *args):
    return CliRunner().invoke(app, ["--project-dir", str(folder), *args])


def _use(folder: pathlib.Path):
    paths.set_project_root(folder)
    return config.load("production")


