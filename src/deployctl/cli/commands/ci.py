@ci_app.command("deploy")
def deploy(
    env: str = env_option(),
    tag: str = typer.Option(None, "--tag", "-t", help="Image tag. Default: the running one (to ship a config "
                            "change), or with --rollback the release before it."),
    rollback: bool = typer.Option(False, "--rollback", help="Roll back instead: never migrates."),
    allow_config_change: bool = typer.Option(
        False, "--allow-config-change", help="Ship config values that differ from what the hosts run."),
    watch: bool = typer.Option(True, "--watch/--no-watch", help="Follow the run until it finishes."),
) -> None:
    """Run the deploy workflow on GitHub — the everyday way to deploy by hand.

    Deploys through the same workflow merges use, with GitHub's copy of the config
    and the CI key, so every deploy lands in one history.
    """
    env_name = resolve_env(env)
    cfg = load_config(env_name)
    _github()
    if not tag:
        running = tags.running(cfg)
        if rollback:
            history = run(cfg, "deploy.sh", ["history"], check=False, capture=True).stdout
            tag = previous_release(parse_history(history, env_name), running) or ""
        else:
            tag = running
        if not tag:
            ui.error("no tag to deploy: pass --tag" + ("" if not rollback else " (no earlier release is recorded)"))
            raise typer.Exit(2)
    try:
        tags.check(tag)
    except tags.NoTag as exc:
        ui.error(str(exc))
        raise typer.Exit(2) from None

    action = "rollback" if rollback else "update"
    started = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(seconds=5)
    try:
        github.dispatch("deploy.yml", cfg.raw["DEPLOY_BRANCH"], {
            "environment": env_name, "tag": tag, "action": action,
            "allow_config_change": "true" if allow_config_change else "false",
        })
    except github.GitHubError as exc:
        ui.error(str(exc))
        ui.hint(f"is deploy.yml on {cfg.raw['DEPLOY_BRANCH']} and the default branch? deployctl ci doctor")
        raise typer.Exit(1) from None
    ui.ok(f"started: {action} {tag} → {env_name} (from {cfg.raw['DEPLOY_BRANCH']})")
    if not watch:
        return

    run_id = None
    for _ in range(20):  # the run appears a few seconds after the dispatch
        for item in github.runs("deploy.yml", limit=5, event="workflow_dispatch"):
            created = datetime.datetime.fromisoformat(item["createdAt"].replace("Z", "+00:00"))
            if created >= started:
                run_id = item["databaseId"]
                ui.info(item["url"])
                break
        if run_id:
            break
        time.sleep(3)
    if not run_id:
        ui.warn("started, but the run did not show up to follow — see: deployctl ci runs")
        return
    raise typer.Exit(github.watch(run_id))


def deploy_runs(cfg: Config, limit: int = 10) -> list[dict]:
    """Deploys through GitHub, newest first: manual ones, and those a push to the deploy branch ran."""
    out = []
    for item in github.runs("deploy.yml", limit=limit, event="workflow_dispatch"):
        title = item.get("displayTitle", "")
        parts = title.split()
        out.append({
            "at": item["createdAt"], "trigger": "manual",
            "action": parts[0] if parts else "update", "tag": parts[1] if len(parts) > 1 else "",
            "status": item.get("conclusion") or item.get("status", ""), "url": item["url"],
        })
    for item in github.runs(OWNED, limit=limit, branch=cfg.raw["DEPLOY_BRANCH"], event="push"):
        job = next((j for j in github.run_jobs(item["databaseId"])
                    if j.get("name", "").lower().startswith("deploy")), None)
        if job is None or job.get("conclusion") == "skipped":
            continue
        out.append({
            "at": item["createdAt"], "trigger": "merge", "action": "update", "tag": item["headSha"][:7],
            "status": job.get("conclusion") or job.get("status", ""), "url": item["url"],
        })
    return sorted(out, key=lambda r: r["at"], reverse=True)[:limit]


@ci_app.command("runs")
def runs(
    env: str = env_option(),
    limit: int = typer.Option(10, "--limit", "-n", help="How many."),
    as_json: bool = typer.Option(False, "--json", help="Machine-readable, for the control panel."),
) -> None:
    """Recent deploys through GitHub — manual and on merge — with their outcome."""
    cfg = load_config(env, require_valid=False)
    _github()
    found = deploy_runs(cfg, limit)
    if as_json:
        print(json.dumps(found, indent=2))
        return
    if not found:
        ui.warn("no deploys through GitHub yet")
        return
    for item in found:
        print(f"  {item['at']}  {item['status'] or '…':<10} {item['action']:<9} {item['tag']:<10} "
              f"{item['trigger']:<7} {item['url']}")


@ci_app.command("auto-deploy")
def auto_deploy(
    state: str = typer.Argument(..., help="on or off"),
    env: str = env_option(),
) -> None:
    """Turn deploy-on-merge on or off (the repository variable AUTO_DEPLOY)."""
    if state not in ("on", "off"):
        ui.error("say on or off")
        raise typer.Exit(2)
    cfg = load_config(env, require_valid=False)
    _github()
    try:
        # Repository level whatever CI_SCOPE says: ci.yml reads it in a job's `if`,
        # before any environment is entered.
        github.set_variable("AUTO_DEPLOY", "true" if state == "on" else "false", None)
    except github.GitHubError as exc:
        ui.error(str(exc))
        raise typer.Exit(1) from None
    if state == "on":
        ui.ok(f"on — every push to {cfg.raw['DEPLOY_BRANCH']} that passes its checks deploys itself")
    else:
        ui.ok("off — deploy with: deployctl ci deploy")
