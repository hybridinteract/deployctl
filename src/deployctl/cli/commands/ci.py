"""``deployctl ci`` — CI/CD: the workflows, GitHub's secrets, and deploying through it.

Every manual step of setting up continuous deployment is a command here, in the
order a project goes through them:

    ci connect      gh logged in, which repository, which plan → CI_SCOPE
    ci init         .github/workflows: build-image.yml, deploy.yml (+ ci.yml once)
    ci setup-key    a CI-only ssh key on every host, its private half in GitHub
    ci pin-hosts    the hosts' keys from this machine's known_hosts, into GitHub
    ci sync-config  this machine's config/ into GitHub, as one secret
    ci doctor       all of the above, checked
    ci deploy       run the deploy workflow (a tag, a config change, a rollback)
    ci runs         what the workflow deployed, and how it went
    ci auto-deploy  merges to the deploy branch deploy themselves, or not
"""

